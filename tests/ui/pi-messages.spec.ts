import { expect, test } from '../offline';
import { piPage } from './pi-fixture';

test('Pi aligns messages, reveals copy and recorded time on hover, and branches natively', async ({ page, context }) => {
  const fixture = await piPage(page);
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://localhost:5200' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://localhost:5200'); await page.getByTestId('dock-app-pi').click();
  const prompt = page.getByTestId('pi-prompt');
  await expect(prompt).toBeEnabled();
  const text = 'Review this project and explain how the frontend and backend work together. Keep the explanation focused on the main request flow.';
  await prompt.fill(text); await page.getByTestId('pi-send').click();
  await expect(page.getByTestId('pi-messages')).toContainText('Inspecting your project');
  await expect(page.getByRole('button', { name: 'Branch chat' })).toHaveCount(0);
  fixture.finish();
  const user = page.getByRole('article', { name: 'Your message' });
  const reply = page.getByRole('article', { name: 'Pi response' }).filter({ has: page.locator('.pi-message-actions') });
  await expect(reply).toContainText('React and Go');
  const userBox = (await user.boundingBox())!; const replyBox = (await reply.boundingBox())!;
  expect(userBox.width).toBeLessThan(replyBox.width * .8);
  expect(userBox.x).toBeGreaterThan(replyBox.x + 80);
  expect(Math.abs(userBox.x + userBox.width - replyBox.x - replyBox.width)).toBeLessThan(1);
  await page.mouse.move(1400, 900);
  await expect(reply.locator('.pi-message-actions')).toHaveCSS('opacity', '0');
  await user.hover();
  await expect(user.locator('.pi-message-actions')).toHaveCSS('opacity', '1');
  await expect(user.locator('time')).toBeVisible();
  const currentUserBox = (await user.boundingBox())!;
  const actionsBox = (await user.locator('.pi-message-actions').boundingBox())!;
  expect(actionsBox.y).toBeGreaterThanOrEqual(currentUserBox.y + currentUserBox.height);
  expect(Math.abs(actionsBox.x + actionsBox.width - currentUserBox.x - currentUserBox.width)).toBeLessThan(1);
  await user.getByRole('button', { name: 'Copy message' }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(text);
  await reply.hover();
  await expect(reply.locator('time')).toHaveText('2:34 PM');
  await expect(reply.locator('time')).toHaveAttribute('datetime', '2026-09-28T14:34:00.000Z');
  await reply.getByRole('button', { name: 'Copy message' }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('The project uses **React and Go**.\n\nI found the application entry point.');
  await page.screenshot({ path: '/tmp/lumo-pi-messages-light.png', animations: 'disabled' });
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: '/tmp/lumo-pi-messages-dark.png', animations: 'disabled' });
  await reply.getByRole('button', { name: 'Branch chat' }).click();
  await expect.poll(() => fixture.commands.filter((command) => command.type === 'clone').length).toBe(1);
  await expect(prompt).toBeEnabled();
  await expect(reply).toContainText('React and Go');
  expect(fixture.originals.get('first.jsonl')?.some((message) => message.role === 'user')).toBe(true);
  expect(fixture.commands.filter((command) => command.type === 'prompt')).toHaveLength(1);
  await page.mouse.move(1400, 900);
  await reply.getByRole('button', { name: 'Branch chat' }).focus();
  await expect(reply.locator('.pi-message-actions')).toHaveCSS('opacity', '1');
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await reply.hover();
  await page.screenshot({ path: '/tmp/lumo-pi-messages-narrow.png', animations: 'disabled' });
  expect(await page.getByTestId('pi-messages').evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('Pi keeps the original conversation if native branching is cancelled', async ({ page }) => {
  const fixture = await piPage(page);
  await page.goto('http://localhost:5200'); await page.getByTestId('dock-app-pi').click();
  await expect(page.getByTestId('pi-prompt')).toBeEnabled();
  await page.getByTestId('pi-prompt').fill('Original conversation'); await page.getByTestId('pi-send').click();
  await expect(page.getByTestId('pi-messages')).toContainText('Inspecting your project');
  fixture.finish();
  await page.route('**/api/v1/pi/command', (route) => route.request().postDataJSON().command.type === 'clone'
    ? route.fulfill({ json: { ok: true, data: { success: true, data: { cancelled: true } } } }) : route.fallback());
  const reply = page.getByRole('article', { name: 'Pi response' }).filter({ has: page.locator('.pi-message-actions') });
  await expect(page.getByTestId('pi-work-segment').locator(':scope > .disclosure-body').first()).toHaveCSS('opacity', '0');
  await reply.hover();
  await expect(reply.locator('.pi-message-actions')).toHaveCSS('opacity', '1');
  await reply.getByRole('button', { name: 'Branch chat' }).click();
  await expect(page.getByRole('alert')).toContainText('Pi cancelled the branch');
  await expect(page.getByTestId('pi-messages')).toContainText('Original conversation');
  expect(fixture.originals.size).toBe(0);
  expect(fixture.commands.filter((command) => command.type === 'prompt')).toHaveLength(1);
});

test('Thinking and tool disclosures stay compact, align icons and animate in both directions', async ({ page }) => {
  await piPage(page);
  await page.route('**/api/v1/pi/command', (route) => route.request().postDataJSON().command.type === 'get_messages' ? route.fulfill({ json: { ok: true, data: { success: true, eventCursor: 0, data: { messages: Array.from({ length: 4 }, (_, index) => [{ role: 'assistant', timestamp: Date.now(), content: [{ type: 'thinking', thinking: 'Review the next step.\n\nCheck the tool output.' }] }, { role: 'toolResult', toolName: index === 0 ? 'read' : 'bash', args: index === 0 ? { path: '/workspace/src/notes.txt' } : undefined, toolCallId: `bash-${index}`, isError: index === 1, content: [{ type: 'text', text: 'Command output\nMore detail' }] }]).flat() } } } }) : route.fallback());
  await page.goto('http://localhost:5200'); await page.getByTestId('dock-app-pi').click();
  const thinking = page.locator('.pi-thinking'); const tools = page.getByTestId('pi-tool');
  await expect(thinking).toHaveCount(4);
  await expect(tools.first().getByRole('button')).toHaveAccessibleName('Read notes.txt Done');
  expect(await page.getByTestId('pi-messages').evaluate((node) => { const heading = node.querySelector('.pi-work-summary')!.getBoundingClientRect(); const thinking = node.querySelector('.pi-thinking .pi-step-label>span')!.getBoundingClientRect(); const tool = node.querySelector('.pi-tool .pi-step-label>span')!.getBoundingClientRect(); return Math.abs((thinking.top - heading.bottom) - (tool.top - thinking.bottom)); })).toBeLessThan(1);
  await expect(tools.first()).toHaveCSS('border-top-width', '0px');
  await expect(tools.first()).toHaveCSS('border-radius', '0px');
  await expect(thinking.first().locator('.pi-step-label svg')).toHaveCount(1);
  await expect(tools.first().locator('.pi-step-label svg')).toHaveCount(1);
  const firstHeight = await thinking.first().evaluate((node) => node.clientHeight);
  expect(firstHeight).toBeLessThanOrEqual(28);
  expect(await tools.first().evaluate((node) => node.clientHeight)).toBeLessThanOrEqual(28);
  const thinkingLabel = (await thinking.first().locator('.pi-step-label').boundingBox())!;
  const toolLabel = (await tools.first().locator('.pi-step-label').boundingBox())!;
  expect(Math.abs(thinkingLabel.x - toolLabel.x)).toBeLessThan(1);
  expect(await page.getByTestId('pi-messages').evaluate((node) => { const first = node.querySelector('.pi-thinking')!.getBoundingClientRect(); const tool = node.querySelector('.pi-tool')!.getBoundingClientRect(); return tool.y - first.y - first.height; })).toBeLessThanOrEqual(8);
  expect(await page.locator('.pi-message-activity .pi-message-actions').count()).toBe(0);
  const trigger = thinking.first().getByRole('button');
  expect(await trigger.evaluate((node) => { const icon = node.querySelector('svg')!.getBoundingClientRect(); const label = node.querySelector('span')!.getBoundingClientRect(); return Math.abs(icon.y + icon.height / 2 - label.y - label.height / 2); })).toBeLessThan(1);
  await trigger.click(); await expect(trigger).toHaveAttribute('aria-expanded', 'true');
  await expect(thinking.first().locator('.disclosure-body')).toHaveCSS('opacity', '1');
  expect((await thinking.first().boundingBox())!.height).toBeGreaterThan(firstHeight + 30);
  await trigger.click(); await expect(trigger).toHaveAttribute('aria-expanded', 'false');
  await expect(thinking.first().locator('.disclosure-body')).toHaveCSS('opacity', '0');
  await expect.poll(async () => Math.abs((await thinking.first().boundingBox())!.height - firstHeight)).toBeLessThan(1);
  await page.screenshot({ path: '/tmp/lumo-pi-activity-light.png', animations: 'disabled' });
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await tools.first().getByRole('button').click();
  expect(await tools.first().locator('.disclosure-body').evaluate((node) => parseFloat(getComputedStyle(node).transitionDuration))).toBeLessThanOrEqual(.00001);
  await page.screenshot({ path: '/tmp/lumo-pi-activity-dark.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/lumo-pi-activity-narrow.png', animations: 'disabled' });
  expect(await page.getByTestId('pi-messages').evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
});
