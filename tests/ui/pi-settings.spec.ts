test('Pi settings keeps a draft on save conflict and can reload server changes', async ({ page }) => {
  await piPage(page);
  let external = false;
  await page.route('**/api/v1/pi/settings**', (route) => {
    if (route.request().method() === 'POST') { external = true; return route.fulfill({ status: 409, json: { ok: false, error: { code: 'conflict', message: 'Instructions changed on the server. Reload before saving.' } } }); }
    if (!external) return route.fallback();
    return route.fulfill({ json: { ok: true, data: { kind: 'instructions', path: '/home/user/.pi/agent/AGENTS.md', content: 'Changed over SSH', revision: 'new-revision', exists: true } } });
  });
  await page.goto('http://localhost:5200'); await page.getByTestId('dock-app-pi').click();
  await page.getByTestId('pi-settings-button').click();
  await page.getByRole('tab', { name: 'Instructions', exact: true }).click();
  await page.getByTestId('pi-instructions').fill('My pending changes');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('changed on the server');
  await expect(page.getByTestId('pi-instructions')).toHaveValue('My pending changes');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Reload instructions', exact: true }).click();
  await expect(page.getByTestId('pi-instructions')).toHaveValue('Changed over SSH');
});

test('Pi keeps Home and Settings at opposite rail ends and supports vertical keyboard tabs', async ({ page }) => {
  const fixture = await piPage(page);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('http://localhost:5200'); await page.getByTestId('dock-app-pi').click();
  await expect(page.getByTestId('pi-prompt')).toBeEnabled();
  await page.getByTestId('pi-prompt').fill('Keep the chat draft');
  const home = page.getByTestId('pi-home-button'); const settings = page.getByTestId('pi-settings-button');
  const homeBox = (await home.boundingBox())!; const settingsBox = (await settings.boundingBox())!;
  expect(settingsBox.y).toBeGreaterThan(homeBox.y + 200);
  expect(settingsBox.x).toBe(homeBox.x);
  await settings.click();
  await expect(settings).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('button', { name: 'Back', exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Providers', exact: true }).focus();
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('tab', { name: 'Instructions', exact: true })).toBeFocused();
  await expect(page.getByRole('tab', { name: 'Instructions', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByTestId('pi-instructions').fill('Unfinished settings draft');
  await home.click();
  await expect(home).toHaveAttribute('aria-current', 'page');
  await expect(page.getByTestId('pi-prompt')).toHaveValue('Keep the chat draft');
  await settings.click();
  await expect(page.getByTestId('pi-instructions')).toHaveValue('Unfinished settings draft');
  expect(fixture.starts).toHaveLength(1);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '/tmp/lumo-pi-settings-rail-light.png', animations: 'disabled' });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: '/tmp/lumo-pi-settings-rail-dark.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '/tmp/lumo-pi-settings-rail-narrow.png', animations: 'disabled' });
  expect(await page.getByTestId('app-pi').evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
  await expect(home).toBeVisible(); await expect(settings).toBeVisible();
});
